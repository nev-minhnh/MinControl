// Precompiles the protocol JSON schemas (../protocol) and the cloud-local schemas (./schemas) into a
// standalone ESM module. Workers forbid runtime code generation (new Function / eval), so ajv cannot
// compile inside the Worker, not even at module load; this script does it at build time instead.
// Usage: npm run gen:validators   (re-run whenever a schema changes; the output is committed)
import Ajv2020 from "ajv/dist/2020.js";
import standaloneCode from "ajv/dist/standalone/index.js";
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const protocolDir = join(here, "..", "..", "protocol");
const localDir = join(here, "..", "schemas");
const outFile = join(here, "..", "src", "generated", "validators.js");

// RFC 3339 date-time, inlined as a RegExp so the generated code has no runtime dependency on ajv-formats.
const DATE_TIME =
  /^\d{4}-(0[1-9]|1[0-2])-(0[1-9]|[12]\d|3[01])[Tt]([01]\d|2[0-3]):[0-5]\d:([0-5]\d|60)(\.\d+)?([Zz]|[+-]([01]\d|2[0-3]):[0-5]\d)$/;

const ajv = new Ajv2020({
  allErrors: false,
  strict: true,
  strictTypes: false,
  strictRequired: false,
  code: { source: true, esm: true, lines: false },
});
ajv.addFormat("date-time", DATE_TIME);

const load = (dir) =>
  readdirSync(dir)
    .filter((f) => f.endsWith(".schema.json"))
    .map((f) => JSON.parse(readFileSync(join(dir, f), "utf8")));
for (const s of [...load(protocolDir), ...load(localDir)]) ajv.addSchema(s);

const P = "https://mincontrol.local/protocol/";
const C = "https://mincontrol.local/cloud/";
const exportsMap = {
  validateSignedEnvelope: P + "signed-envelope.schema.json",
  validateSignedBody: P + "signed-body.schema.json",
  validatePolicy: P + "policy.schema.json",
  validateCommand: P + "command.schema.json",
  validateCommandAck: P + "command-ack.schema.json",
  validateEvent: P + "event.schema.json",
  validateEventBatch: P + "event-batch.schema.json",
  validateEnrollRequest: C + "enroll-request.schema.json",
  validateMasterRegister: C + "master-register.schema.json",
  validatePushSubscribe: C + "push-subscribe.schema.json",
  validateDeviceState: C + "device-state.schema.json",
  validateWsDeviceMessage: C + "ws-device-message.schema.json",
};
// ajv's ESM output still require()s two tiny runtime helpers; inline them so the module is pure ESM.
const RUNTIME = {
  'require("ajv/dist/runtime/ucs2length").default':
    "((s) => { let n = 0; for (const _ of s) n++; return n; })",
  'require("ajv/dist/runtime/equal").default':
    "(function eq(a, b) { if (a === b) return true; if (a && b && typeof a === 'object' && typeof b === 'object') {" +
    " if (Array.isArray(a) !== Array.isArray(b)) return false;" +
    " const ka = Object.keys(a), kb = Object.keys(b); if (ka.length !== kb.length) return false;" +
    " for (const k of ka) { if (!Object.prototype.hasOwnProperty.call(b, k) || !eq(a[k], b[k])) return false; } return true; }" +
    " return a !== a && b !== b; })",
};
let code = standaloneCode(ajv, exportsMap);
for (const [from, to] of Object.entries(RUNTIME)) code = code.split(from).join(to);
if (/require\(/.test(code)) throw new Error("generated code still contains require(): " + code.match(/require\([^)]*\)/)[0]);
mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, "// @ts-nocheck\n// GENERATED by scripts/gen-validators.mjs from protocol/*.schema.json and cloud/schemas - do not edit.\n" + code);
console.log("wrote", outFile, code.length, "bytes");
